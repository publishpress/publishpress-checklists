    /** @since 2.31.0 */
    public static function plan(array $input)
    {
        $before = Catalog::get($input);
        if (is_wp_error($before)) {
            return $before;
        }
        if (!$before['requirement']->available) {
            return Registry::error(__('This requirement needs its active Pro integration.', 'publishpress-checklists'), 403);
        }
        if ($before['hash'] !== $input['expected_hash']) {
            return Registry::error(__('Checklist configuration changed. Read it again.', 'publishpress-checklists'), 409);
        }
        $valid = Registry::validate($input['settings'], $before['schema']);
        if (is_wp_error($valid)) {
            return $valid;
        }
        if (isset($input['settings']['title']) && empty(sanitize_textarea_field($input['settings']['title']))) {
            return Registry::error(__('Enter a task title that remains non-empty after sanitization.', 'publishpress-checklists'));
        }
        $instance = Catalog::instances($input['post_type'])[$input['requirement']];
        if (array_key_exists('users', $input['settings'])) {
            if (!current_user_can('list_users')) {
                return Registry::error(__('You cannot select users.', 'publishpress-checklists'), 403);
            }
            foreach ($input['settings']['users'] as $userId) {
                $user = ctype_digit($userId) ? get_user_by('id', (int) $userId) : false;
                if (!$user || (string) $user->ID !== $userId || !user_can($user, 'edit_posts')) {
                    return Registry::error(__('Select an eligible user from current choices.', 'publishpress-checklists'));
                }
            }
        }
        $taxonomy = Catalog::taxonomy($instance);
        if ($taxonomy && array_key_exists('multiple', $input['settings'])) {
            $object = get_taxonomy($taxonomy);
            if (!$object || !current_user_can($object->cap->assign_terms)) {
                return Registry::error(__('You cannot assign this taxonomy.', 'publishpress-checklists'), 403);
            }
            foreach ($input['settings']['multiple'] as $token) {
                $parts = explode('__', $token, 2);
                $term = ctype_digit($parts[0]) ? get_term((int) $parts[0], $taxonomy) : null;
                if (!$term || is_wp_error($term) || $token !== $term->term_id . '__' . $term->name) {
                    return Registry::error(__('Read current taxonomy choices before saving.', 'publishpress-checklists'));
                }
            }
        }
        $patch = [];
        foreach ($input['settings'] as $suffix => $value) {
            $key = $input['requirement'] . '_' . $suffix;
            $patch[$key] = [$input['post_type'] => $value];
            if ($suffix === 'rule') {
                $patch[$input['requirement']] = [$input['post_type'] => $value === Plugin::RULE_DISABLED ? 'no' : 'yes'];
            }
        }
        $nextValues = array_merge((array) $before['settings'], $input['settings']);
        if (isset($nextValues['min'], $nextValues['max']) && $nextValues['min'] !== '' && $nextValues['max'] !== ''
            && $nextValues['max'] > 0 && $nextValues['min'] > $nextValues['max']) {
            return Registry::error(__('The minimum cannot exceed a positive maximum.', 'publishpress-checklists'));
        }
        if (array_key_exists('can_ignore', $input['settings']) && !Settings::get()['settings']->who_can_ignore_option) {
            return Registry::error(__('Enable Who can ignore in Settings before changing role exceptions.', 'publishpress-checklists'));
        }
        return ['before' => $before, 'patch' => $patch];
    }

    /** @since 2.31.0 */
    public static function update(array $input)
    {
        $result = self::bulk(['changes' => [$input], 'dry_run' => !empty($input['dry_run'])]);
        return is_wp_error($result) ? $result : $result['results'][0];
    }

    /** @since 2.31.0 */
    public static function bulk(array $input)
    {
        $raw = [];
        $plans = $seen = [];
        foreach ($input['changes'] as $change) {
            $target = $change['post_type'] . ':' . $change['requirement'];
            if (isset($seen[$target])) {
                return Registry::error(__('Include each requirement/post-type target only once.', 'publishpress-checklists'));
            }
            $plan = self::plan($change);
            if (is_wp_error($plan)) {
                return $plan;
            }
            $plans[] = $change;
            $seen[$target] = true;
            foreach ($plan['patch'] as $key => $value) {
                $raw[$key] = array_merge((array) ($raw[$key] ?? []), $value);
            }
        }
        $native = Options::legacy()->checklists->validate_configuration_patch($raw);
        foreach ($plans as $change) {
            $projected = Catalog::get($change, $native);
            if (is_wp_error($projected)) {
                return $projected;
            }
            $valid = Registry::validate(array_intersect_key((array) $projected['settings'], $change['settings']), $projected['schema']);
            if (is_wp_error($valid)) {
                return $valid;
            }
        }
        if (empty($input['dry_run'])) {
            $saved = Options::save('checklists', $native);
            if (is_wp_error($saved)) {
                return $saved;
            }
        }
        $results = [];
        foreach ($plans as $change) {
            $state = Catalog::get($change, !empty($input['dry_run']) ? $native : null);
            $state['dry_run'] = !empty($input['dry_run']);
            if ($state['dry_run']) {
                $state['hash'] = $change['expected_hash'];
            }
            $results[] = $state;
        }
        return ['results' => $results, 'dry_run' => !empty($input['dry_run'])];
    }

    /** @since 2.31.0 */
    public static function custom(array $input)
    {
        if (!isset(Options::legacy()->settings->getAllPostTypes()[$input['post_type']])) {
            return Registry::error(__('Choose a supported post type.', 'publishpress-checklists'));
        }
        $raw = Options::read('checklists');
        $kind = $input['kind'] ?? 'custom';
        $existing = !empty($input['id']);
        if ($existing) {
            $item = Catalog::instances($input['post_type'])[$input['id']] ?? null;
            if (!$item || !($item instanceof Custom_item || $item instanceof Openai_item)) {
                return Registry::error(__('Choose a configured custom or OpenAI task.', 'publishpress-checklists'));
            }
            if (isset($input['kind']) && $input['kind'] !== ($item instanceof Openai_item ? 'openai' : 'custom')) {
                return Registry::error(__('Task kind cannot be changed. Use its discovered kind or create a new task.', 'publishpress-checklists'));
            }
            $state = self::update(['post_type' => $input['post_type'], 'requirement' => $input['id'],
                'settings' => $input['settings'], 'expected_hash' => $input['expected_hash'] ?? '', 'dry_run' => $input['dry_run'] ?? false]);
            return is_wp_error($state) ? $state : ['id' => $input['id'], 'post_type' => $input['post_type'], 'settings' => $state['settings'], 'dry_run' => $state['dry_run']];
        }
        $id = ($kind === 'openai' ? 'openai_item_' : 'custom_item_') . str_replace('-', '', wp_generate_uuid4());
        $class = $kind === 'openai' ? Openai_item::class : Custom_item::class;
        $item = new $class($id, Options::legacy()->checklists->module, $input['post_type']);
        $item->init_language();
        $fields = $item->get_configuration_fields();
        $valid = Registry::validate($input['settings'], Registry::object($fields, ['title']));
        if (is_wp_error($valid)) {
            return $valid;
        }
        if (empty(sanitize_textarea_field($input['settings']['title']))) {
            return Registry::error(__('Enter a task title that remains non-empty after sanitization.', 'publishpress-checklists'));
        }
        if (array_key_exists('can_ignore', $input['settings']) && !Settings::get()['settings']->who_can_ignore_option) {
            return Registry::error(__('Enable Who can ignore in Settings before changing role exceptions.', 'publishpress-checklists'));
        }
        $defaults = ['rule' => Plugin::RULE_DISABLED];
        if ($kind === 'custom') {
            $defaults['editable_by'] = array_keys(\PPCH_Checklists::get_editable_roles_labels());
        }
        $values = array_merge($defaults, $input['settings']);
        $list = $kind === 'openai' ? 'openai_items' : 'custom_items';
        $raw = [$list => array_merge($raw[$list] ?? [], [$id])];
        foreach ($values as $suffix => $value) {
            $raw[$id . '_' . $suffix][$input['post_type']] = $value;
        }
        $raw[$id][$input['post_type']] = $values['rule'] === Plugin::RULE_DISABLED ? 'no' : 'yes';
        $native = Options::legacy()->checklists->validate_configuration_patch($raw);
        $normalized = array_map(static fn($suffix) => $native[$id . '_' . $suffix][$input['post_type']] ?? null, array_combine(array_keys($values), array_keys($values)));
        $valid = Registry::validate($normalized, Registry::object($fields, ['title']));
        if (is_wp_error($valid)) {
            return $valid;
        }
        if (empty($input['dry_run'])) {
            $saved = Options::save('checklists', $native);
            if (is_wp_error($saved)) {
                return $saved;
            }
        }
        return ['id' => !empty($input['dry_run']) ? '' : $id, 'post_type' => $input['post_type'],
            'settings' => (object) $normalized, 'dry_run' => !empty($input['dry_run'])];
    }

    /** @since 2.31.0 */
    public static function delete(array $input)
    {
        $state = Catalog::get($input);
        if (is_wp_error($state)) {
            return $state;
        }
        if (!$state['requirement']->custom && !$state['requirement']->openai) {
            return Registry::error(__('Only custom and OpenAI tasks can be removed.', 'publishpress-checklists'));
        }
        if ($state['hash'] !== $input['expected_hash']) {
            return Registry::error(__('Checklist configuration changed. Read it again.', 'publishpress-checklists'), 409);
        }
        $raw = Options::read('checklists');
        $id = $input['requirement'];
        foreach (array_merge([''], array_keys($state['schema']['properties'])) as $suffix) {
            $key = $id . ($suffix === '' ? '' : '_' . $suffix);
            unset($raw[$key][$input['post_type']]);
            if (empty($raw[$key])) {
                unset($raw[$key]);
            }
        }
        if (empty($raw[$id . '_title'])) {
            foreach (['custom_items', 'openai_items'] as $list) {
                $raw[$list] = array_values(array_diff($raw[$list] ?? [], [$id]));
            }
        }
        if (empty($input['dry_run'])) {
            $saved = Options::save('checklists', $raw);
            if (is_wp_error($saved)) {
                return $saved;
            }
        }
        return ['id' => $id, 'post_type' => $input['post_type'], 'dry_run' => !empty($input['dry_run'])];
    }

    /** @since 2.31.0 */
    public static function reorder(array $input)
    {
        $state = Catalog::get(['post_type' => $input['post_type'], 'requirement' => $input['requirements'][0]]);
        if (is_wp_error($state) || $state['hash'] !== $input['expected_hash']) {
            return Registry::error(__('Checklist configuration changed. Read it again.', 'publishpress-checklists'), 409);
        }
        $known = Catalog::instances($input['post_type']);
        if (array_diff($input['requirements'], array_keys($known))) {
            return Registry::error(__('Use discovered requirement identifiers.', 'publishpress-checklists'));
        }
        $raw = Options::read('checklists');
        $ordered = [];
        foreach ($input['requirements'] as $id) {
            $ordered[$id . '_rule'] = $raw[$id . '_rule'] ?? [$input['post_type'] => Plugin::RULE_DISABLED];
        }
        $ordered += $raw;
        if (empty($input['dry_run'])) {
            $saved = Options::save('checklists', $ordered);
            if (is_wp_error($saved)) {
                return $saved;
            }
        }
        return ['order' => $input['requirements'], 'shared_order' => true, 'dry_run' => !empty($input['dry_run'])];
    }

    /** @since 2.31.0 */
    public static function resetLabels(array $input)
    {
        if (Settings::get()['checklist_hash'] !== $input['expected_hash']) {
            return Registry::error(__('Settings changed. Read them again.', 'publishpress-checklists'), 409);
        }
        $raw = Options::read('checklists');
        foreach (array_keys($raw) as $key) {
            if (preg_match('/(_custom_label|_editor_label)$/D', $key)) {
                unset($raw[$key]);
            }
        }
        if (empty($input['dry_run'])) {
            $saved = Options::save('checklists', $raw);
            if (is_wp_error($saved)) {
                return $saved;
            }
        }
        return ['reset' => empty($input['dry_run']), 'dry_run' => !empty($input['dry_run'])];
    }
